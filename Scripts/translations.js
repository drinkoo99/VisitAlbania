// ============================
// EVENT LISTENER FOR LANGUAGES DROPDOWN
// ============================
function setNavbarLanguage(lang) {
  const elements = document.querySelectorAll('[data-translate]');
  elements.forEach(el => {
    const key = el.getAttribute('data-translate');
    if (translations[lang][key]) {
      // Ruaj ikonën nëse ekziston
      const icon = el.querySelector('i');
      if (icon) {
        el.innerHTML = `${translations[lang][key]} ${icon.outerHTML}`;
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });
}

document.querySelectorAll('#languagesDropdown a').forEach(link => {
  link.addEventListener('click', (e) => {
    e.preventDefault();
    const lang = link.textContent.trim().toLowerCase(); // p.sh. 'albanian'
    setNavbarLanguage(lang);
  });
});